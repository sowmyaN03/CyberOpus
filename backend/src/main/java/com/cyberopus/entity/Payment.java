package com.cyberopus.entity;

import com.cyberopus.enums.PaymentMethod;
import com.cyberopus.enums.PaymentStatus;
import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.Instant;

@Entity
@Table(name = "payments")
@Getter @Setter @NoArgsConstructor @AllArgsConstructor @Builder
public class Payment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "order_id", nullable = false, unique = true)
    private Order order;

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_method", nullable = false, length = 20)
    private PaymentMethod paymentMethod;

    /** Only last-4 masked card info stored – never the full number */
    @Column(name = "masked_card_number", length = 20)
    private String maskedCardNumber;

    @Column(name = "card_holder_name", length = 200)
    private String cardHolderName;

    /** Simulated transaction reference generated by the backend */
    @Column(name = "transaction_ref", unique = true, length = 100)
    private String transactionRef;

    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal amount;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    @Builder.Default
    private PaymentStatus status = PaymentStatus.PENDING;

    @Column(name = "initiated_at", nullable = false)
    private Instant initiatedAt;

    @Column(name = "completed_at")
    private Instant completedAt;

    @PrePersist
    protected void onPrePersist() {
        if (initiatedAt == null) {
            initiatedAt = Instant.now();
        }
    }
}
